/**
 * Returns the curated media collection for a given site ID.
 * @param {string} siteId - Analogue site ID
 * @returns {Array} Array of media items, or empty array if unavailable
 */
export function getSiteMedia(siteId) {
  if (!siteId) return []
  return SITE_MEDIA_MANIFEST[siteId] || []
}

/**
 * Checks whether verified site imagery is available for a given site ID.
 * @param {string} siteId - Analogue site ID
 * @returns {boolean} True if at least one verified image is cataloged
 */
export function hasSiteMedia(siteId) {
  if (!siteId) return false
  const media = SITE_MEDIA_MANIFEST[siteId]
  return Array.isArray(media) && media.length > 0
}

/**
 * Extracts unique categories available for a given site ID.
 * @param {string} siteId - Analogue site ID
 * @returns {string[]} Array of categories e.g. ['overview', 'terrain']
 */
export function getSiteMediaCategories(siteId) {
  const media = getSiteMedia(siteId)
  const cats = new Set(media.map((m) => m.category))
  return Array.from(cats)
}

